#!/bin/bash
# A silver service whose settings page is generated from config/settings.conf.
# The branch adds a `timeout` setting and does not run the generator.
set -eu
. "$(dirname "$0")/../install-qk.sh"
commit() { git add -A && git -c user.name=Eval -c user.email=eval@example.com commit -q -m "$1"; }

git init -q -b main
mkdir -p config scripts docs/reference
cat > quality.yaml <<'YAML'
version: 1
maturity: silver
docs:
  root: docs
  impact_map:
    - paths: ["config/**"]
      docs: ["docs/reference/settings.md"]
generated:
  - file: docs/reference/settings.md
    cmd: sh scripts/gen-settings-doc.sh
YAML
cat > config/settings.conf <<'CONF'
port=8080 # Port the server listens on
log_level=info # How much the server logs
CONF
cat > scripts/gen-settings-doc.sh <<'GEN'
#!/bin/sh
# Writes docs/reference/settings.md from config/settings.conf.
{
	echo '<!-- generated by qk: sh scripts/gen-settings-doc.sh. Do not edit by hand. -->'
	echo '# Settings'
	echo
	echo '| Setting | Default | Meaning |'
	echo '| --- | --- | --- |'
	sed -n 's/^\([a-z_]*\)=\([^ ]*\) *# *\(.*\)$/| `\1` | `\2` | \3 |/p' config/settings.conf
} > docs/reference/settings.md
GEN
sh scripts/gen-settings-doc.sh
commit "Settings and their generated page"

git checkout -q -b add-timeout
echo 'timeout=30 # Seconds before a request is cut off' >> config/settings.conf
commit "Add the timeout setting"
