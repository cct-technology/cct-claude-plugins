package manifest

import (
	"bufio"
	"bytes"
	"encoding/json"
	"fmt"
	"io"
	"maps"
	"slices"
	"strings"
)

// keywords lists the schema constructs the reference generator understands.
// Anything else is an error, so a schema change cannot silently drop keys from the docs.
var keywords = map[string]bool{
	"$schema": true, "$id": true, "title": true, "description": true, "type": true,
	"properties": true, "additionalProperties": true, "required": true, "items": true,
	"enum": true, "const": true, "default": true, "$ref": true, "$defs": true,
	"propertyNames": true, "pattern": true, "minItems": true, "minLength": true,
}

type schemaNode map[string]json.RawMessage

const referenceIntro = "<!-- generated by qk: go run ./cmd/gen-docs. Do not edit by hand. -->\n\n" +
	"# quality.yaml reference\n\n" +
	"`quality.yaml` sits at the repository root. It is optional: without it, every check runs advisory with defaults. " +
	"`qk` validates it against `plugins/quality-kit/schemas/quality.schema.json` (rule QK001).\n\n" +
	"| Key | Value | Description |\n| --- | --- | --- |\n"

// WriteReference writes a table of every key in the JSON Schema, in schema order.
func WriteReference(w io.Writer, schema []byte) error {
	g := &refGen{}
	root, err := g.parse(schema, "(top level)")
	if err != nil {
		return err
	}
	if raw, ok := root["$defs"]; ok {
		if err := json.Unmarshal(raw, &g.defs); err != nil {
			return err
		}
	}
	if err := g.object(root, ""); err != nil {
		return err
	}
	b := bufio.NewWriter(w)
	b.WriteString(referenceIntro)
	for _, r := range g.rows {
		fmt.Fprintf(b, "| `%s` | %s | %s |\n", r[0], r[1], strings.ReplaceAll(r[2], "|", `\|`))
	}
	return b.Flush()
}

type refGen struct {
	defs map[string]json.RawMessage
	rows [][3]string
}

// parse decodes one schema node, rejecting keywords the generator does not handle
// and resolving a local $ref (keys beside the $ref win).
func (g *refGen) parse(raw json.RawMessage, at string) (schemaNode, error) {
	var n schemaNode
	if err := json.Unmarshal(raw, &n); err != nil {
		return nil, fmt.Errorf("%s: %w", at, err)
	}
	for _, k := range slices.Sorted(maps.Keys(n)) {
		if !keywords[k] {
			return nil, fmt.Errorf("unsupported schema keyword %q at %s", k, at)
		}
	}
	ref, ok := n["$ref"]
	if !ok {
		return n, nil
	}
	var target string
	_ = json.Unmarshal(ref, &target)
	name, ok := strings.CutPrefix(target, "#/$defs/")
	if !ok || g.defs[name] == nil {
		return nil, fmt.Errorf("unsupported $ref %q at %s", target, at)
	}
	resolved, err := g.parse(g.defs[name], at)
	if err != nil {
		return nil, err
	}
	for k, v := range n {
		if k != "$ref" {
			resolved[k] = v
		}
	}
	return resolved, nil
}

// object adds a row for each property of n, then recurses into nested objects.
func (g *refGen) object(n schemaNode, prefix string) error {
	raw, ok := n["properties"]
	if !ok {
		return nil
	}
	var props map[string]json.RawMessage
	if err := json.Unmarshal(raw, &props); err != nil {
		return err
	}
	order, err := objectKeys(raw)
	if err != nil {
		return err
	}
	var required []string
	_ = json.Unmarshal(n["required"], &required)

	for _, key := range order {
		path := prefix + key
		p, err := g.parse(props[key], path)
		if err != nil {
			return err
		}
		desc := str(p["description"])
		if desc == "" {
			return fmt.Errorf("no description for %s", path)
		}
		value, err := g.describe(p, path)
		if err != nil {
			return err
		}
		if slices.Contains(required, key) {
			value += "; required"
		}
		if d, ok := p["default"]; ok {
			value += "; default `" + literal(d) + "`"
		}
		g.rows = append(g.rows, [3]string{path, value, desc})

		switch str(p["type"]) {
		case "object":
			err = g.object(p, path+".")
		case "array":
			var items schemaNode
			if items, err = g.parse(p["items"], path+"[]"); err == nil {
				err = g.object(items, path+"[].")
			}
		}
		if err != nil {
			return err
		}
	}
	return nil
}

// describe says what values a key takes.
func (g *refGen) describe(n schemaNode, at string) (string, error) {
	if c, ok := n["const"]; ok {
		return "`" + literal(c) + "`", nil
	}
	if e, ok := n["enum"]; ok {
		var vals []json.RawMessage
		if err := json.Unmarshal(e, &vals); err != nil {
			return "", err
		}
		quoted := make([]string, len(vals))
		for i, v := range vals {
			quoted[i] = "`" + literal(v) + "`"
		}
		if len(quoted) == 1 {
			return quoted[0], nil
		}
		return strings.Join(quoted[:len(quoted)-1], ", ") + " or " + quoted[len(quoted)-1], nil
	}
	switch t := str(n["type"]); t {
	case "string":
		return "string", nil
	case "boolean":
		return "`true` or `false`", nil
	case "integer", "number":
		return "number", nil
	case "array":
		items, err := g.parse(n["items"], at+"[]")
		if err != nil {
			return "", err
		}
		switch str(items["type"]) {
		case "string":
			return "list of strings", nil
		case "object":
			return "list of objects", nil
		}
		return "", fmt.Errorf("cannot describe the items of %s", at)
	case "object":
		ap := n["additionalProperties"]
		if len(ap) == 0 || ap[0] != '{' {
			return "object", nil
		}
		val, err := g.parse(ap, at+".*")
		if err != nil {
			return "", err
		}
		valDesc, err := g.describe(val, at+".*")
		if err != nil {
			return "", err
		}
		noun := "keys"
		if pn, ok := n["propertyNames"]; ok {
			names, err := g.parse(pn, at)
			if err != nil {
				return "", err
			}
			if d := str(names["description"]); d != "" {
				noun = d
			}
		}
		return "map of " + noun + " to " + valDesc, nil
	default:
		return "", fmt.Errorf("cannot describe type %q at %s", t, at)
	}
}

// objectKeys returns a JSON object's keys in document order.
func objectKeys(raw json.RawMessage) ([]string, error) {
	dec := json.NewDecoder(bytes.NewReader(raw))
	if _, err := dec.Token(); err != nil { // {
		return nil, err
	}
	var keys []string
	for dec.More() {
		tok, err := dec.Token()
		if err != nil {
			return nil, err
		}
		keys = append(keys, tok.(string))
		var skip json.RawMessage
		if err := dec.Decode(&skip); err != nil {
			return nil, err
		}
	}
	return keys, nil
}

func str(raw json.RawMessage) string {
	var s string
	_ = json.Unmarshal(raw, &s)
	return s
}

// literal renders a JSON value for prose: strings without quotes, the rest as written.
func literal(raw json.RawMessage) string {
	if s := str(raw); s != "" {
		return s
	}
	return string(raw)
}
