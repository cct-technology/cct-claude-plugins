package check

import (
	"bufio"
	"encoding/json"
	"fmt"
	"io"
	"strings"
)

// Formats lists the report formats WriteReport accepts.
var Formats = []string{"text", "json", "claude"}

// WriteReport writes rep to w in the named format.
func WriteReport(w io.Writer, rep Report, format string) error {
	switch format {
	case "text":
		return writeText(w, rep)
	case "json":
		enc := json.NewEncoder(w)
		enc.SetEscapeHTML(false)
		enc.SetIndent("", "  ")
		if rep.Results == nil {
			rep.Results = []RuleResult{}
		}
		return enc.Encode(rep)
	case "claude":
		return writeClaude(w, rep)
	}
	return fmt.Errorf("unknown format %q (want one of %s)", format, strings.Join(Formats, ", "))
}

func writeText(w io.Writer, rep Report) error {
	b := bufio.NewWriter(w)
	for _, r := range rep.Results {
		label := strings.ToUpper(string(r.Status))
		if r.Status == Skipped {
			label = "SKIP"
		}
		fmt.Fprintf(b, "%s  %s  %s (%s)\n", label, r.Rule, r.Title, r.Mode)
		for _, f := range r.Findings {
			fmt.Fprintf(b, "      - %s\n", findingLine(f))
		}
		for _, w := range r.Waived {
			fmt.Fprintf(b, "      waived: %s (%s until %s: %s)\n", findingLine(Finding{File: w.File, Message: w.Message}), w.Owner, w.Expires, w.Reason)
		}
		if r.Fix != "" {
			fmt.Fprintf(b, "      fix: %s\n", r.Fix)
		}
		if r.Reason != "" {
			fmt.Fprintf(b, "      skipped: %s\n", r.Reason)
		}
	}
	s := rep.Summary
	fmt.Fprintf(b, "\n%d fail, %d warn, %d pass, %d skipped", s.Fail, s.Warn, s.Pass, s.Skipped)
	if s.Waived > 0 {
		fmt.Fprintf(b, ", %d waived", s.Waived)
	}
	if rep.Blocking {
		b.WriteString(" (blocking)")
	}
	b.WriteString("\n")
	return b.Flush()
}

// writeClaude lists what an agent must act on (rule, file, what to do), then
// names what needs no action: waived findings, and every skipped check, so a
// check that could not run never reads as a pass.
func writeClaude(w io.Writer, rep Report) error {
	b := bufio.NewWriter(w)
	s := rep.Summary
	if s.Fail+s.Warn == 0 {
		b.WriteString("Quality Kit: no findings.\n")
	} else {
		fmt.Fprintf(b, "Quality Kit: %d fail, %d warn.\n", s.Fail, s.Warn)
	}
	var waived, skipped []string
	for _, r := range rep.Results {
		for _, w := range r.Waived {
			waived = append(waived, strings.TrimSpace(r.Rule+" "+w.File)+" (until "+w.Expires+")")
		}
		switch r.Status {
		case Fail, Warn:
			fmt.Fprintf(b, "%s %s: %s\n", r.Rule, r.Status, r.Title)
			for _, f := range r.Findings {
				fmt.Fprintf(b, "- %s\n", findingLine(f))
			}
			fmt.Fprintf(b, "Fix: %s More: qk explain %s\n", r.Fix, r.Rule)
		case Skipped:
			skipped = append(skipped, fmt.Sprintf("%s (%s)", r.Rule, r.Reason))
		}
	}
	if len(waived) > 0 {
		fmt.Fprintf(b, "Waived: %s\n", strings.Join(waived, ", "))
	}
	if len(skipped) > 0 {
		fmt.Fprintf(b, "Skipped: %s\n", strings.Join(skipped, ", "))
	}
	return b.Flush()
}

func findingLine(f Finding) string {
	if f.File == "" {
		return f.Message
	}
	return f.File + ": " + f.Message
}

const referenceIntro = `<!-- generated by qk: go run ./cmd/gen-docs. Do not edit by hand. -->

# Rule reference

Every rule that ` + "`qk check`" + ` runs. Rule IDs are stable and never reused.

A rule's mode decides what a failure does: ` + "`enforced`" + ` blocks, ` + "`advisory`" + ` warns, ` + "`off`" + ` skips the rule. The ` + "`maturity`" + ` in ` + "`quality.yaml`" + ` sets the default mode. Override it per check under ` + "`modes`" + `, using the check key. Without a ` + "`quality.yaml`" + `, every rule is advisory.
`

// WriteReference writes the generated rule reference for rules.
func WriteReference(w io.Writer, rules []Rule) error {
	if _, err := io.WriteString(w, referenceIntro); err != nil {
		return err
	}
	if len(rules) == 0 {
		_, err := io.WriteString(w, "\nNo rules are registered yet.\n")
		return err
	}
	for _, r := range rules {
		if _, err := io.WriteString(w, "\n"); err != nil {
			return err
		}
		if err := WriteRule(w, r); err != nil {
			return err
		}
	}
	return nil
}

// WriteRule writes one rule's reference section; `qk explain` prints the same.
func WriteRule(w io.Writer, r Rule) error {
	var levels []string
	for m := r.EnforcedFrom; m <= Gold; m++ {
		levels = append(levels, m.String())
	}
	_, err := fmt.Fprintf(w, "## %s — %s\n\n- Check key: `%s`\n- Phase: %d\n- Enforced by default at: %s\n\n**What it checks.** %s\n\n**How to fix.** %s\n",
		r.ID, r.Title, r.Check, r.Phase, strings.Join(levels, ", "), r.Why, r.Fix)
	return err
}
